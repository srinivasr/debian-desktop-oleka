#!/usr/bin/env python3
"""Render component themes from theme/palette.toml (stdlib only, Python 3.11+).

Writes into config/includes.chroot/etc/skel/.config so every component
(sway, waybar, foot, the launcher) shares one palette.
"""
import pathlib
import re
import sys

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11: tiny reader for our flat palette file
    tomllib = None

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKEL = ROOT / "config/includes.chroot/etc/skel/.config"


def _mini_toml(text):
    """Reads only what palette.toml uses: [tables], key = "str" / int."""
    out, cur = {}, None
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            cur = out.setdefault(line.strip("[]"), {})
            continue
        k, v = (x.strip() for x in line.split("=", 1))
        v = int(v) if v.isdigit() else v.strip('"')
        (cur if cur is not None else out)[k] = v
    return out


def load(path=ROOT / "theme/palette.toml"):
    if tomllib:
        with open(path, "rb") as f:
            return tomllib.load(f)
    return _mini_toml(pathlib.Path(path).read_text())


def hexno(c):
    return c.lstrip("#")


def sway_colors(p):
    c = p["colors"]
    return f"""# generated by scripts/gen-theme.py, do not edit
set $bg {c['bg']}
set $surface {c['surface']}
set $text {c['text']}
set $muted {c['muted']}
set $accent {c['accent']}
set $urgent {c['urgent']}
client.focused          $accent  $surface $text $accent  $accent
client.focused_inactive $surface $bg      $muted $surface $surface
client.unfocused        $surface $bg      $muted $surface $surface
client.urgent           $urgent  $urgent  $bg    $urgent  $urgent
"""


def waybar_css(p):
    c, r = p["colors"], p["radius"]
    return f"""/* generated by scripts/gen-theme.py, edit waybar/style.base.css for layout */
@define-color bg {c['bg']};
@define-color surface {c['surface']};
@define-color text {c['text']};
@define-color muted {c['muted']};
@define-color accent {c['accent']};
@define-color warn {c['warn']};
@define-color urgent {c['urgent']};
* {{ font-family: {p['font']}; font-size: 13px; border-radius: {r}px; }}
"""


def foot_ini(p):
    c = p["colors"]
    return f"""# generated by scripts/gen-theme.py
[main]
font={p['mono'].split(',')[0]}:size=11
[colors]
background={hexno(c['bg'])}
foreground={hexno(c['text'])}
regular0={hexno(c['surface'])}
regular1={hexno(c['urgent'])}
regular4={hexno(c['accent'])}
regular3={hexno(c['warn'])}
"""


def launcher_css(p):
    """The launcher owns its layout in launcher/style.css; we only rewrite its palette lines."""
    c = p["colors"]
    text = (ROOT / "launcher/style.css").read_text()
    for name in ("bg", "surface", "text", "accent", "muted"):
        text = re.sub(r"(@define-color %s\s+)#[0-9a-fA-F]{6};" % name, r"\g<1>%s;" % c[name], text)
    return text


def render(p):
    return {
        SKEL / "sway/colors.conf": sway_colors(p),
        SKEL / "waybar/palette.css": waybar_css(p),
        SKEL / "foot/foot.ini": foot_ini(p),
        ROOT / "launcher/style.css": launcher_css(p),
    }


def main():
    p = load()
    for path, text in render(p).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
